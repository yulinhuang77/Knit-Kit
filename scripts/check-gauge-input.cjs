const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../assets/index-cUViE75_.js'), 'utf8');
const start = source.indexOf('function KgCount(');
const end = source.indexOf('const Fu=', start);
assert.ok(start >= 0 && end > start, 'gauge conversion helpers must exist');
const context = {};
vm.createContext(context);
vm.runInContext(source.slice(start, end) + ';this.KgCount=KgCount;this.KgMm=KgMm;', context);
assert.equal(context.KgCount(2.5), 40);
assert.equal(context.KgCount(100 / 60), 60);
assert.equal(context.KgMm('40'), 2.5);
assert.equal(context.KgMm('60.5'), 100 / 60.5);
assert.equal(context.KgMm('40,5'), 100 / 40.5);
assert.equal(context.KgMm(''), null);
assert.equal(context.KgMm('0'), null);
assert.equal(context.KgMm('501'), null);
assert.match(source, /横向：10 cm = X 针[\s\S]{0,350}type:"text"[\s\S]{0,200}inputMode:"decimal"/);
assert.match(source, /纵向：10 cm = Y 排[\s\S]{0,350}type:"text"[\s\S]{0,200}inputMode:"decimal"/);
assert.ok(!source.includes('value:o.gauge.stitchWidthMm,onChange:p=>pt("stitchWidthMm"'), 'density input must not be controlled');
assert.ok(source.includes('p.key==="Enter"&&p.currentTarget.blur()'), 'Enter must commit through blur');
console.log('PASS: 10 cm gauge conversion and Safari-editable uncontrolled density inputs');
